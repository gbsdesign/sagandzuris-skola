// The index of „ძებნა სიმღერით“ (2026-11-18): for every chant that has a version with book notes in this repo, the top voice's
// first 16 pitches (MIDI, a repeated pitch once) — what a hummed tune is compared with (utils/humMatch.ts). The anthology's
// notes live on R2 (not here), so a chant that has only those is left out. Writes src/data/humIndex.ts:
//   node scripts/build-hum-index.mjs
import fs from 'node:fs';
import path from 'node:path';
import { appData, ROOT } from './lib/appData.mjs';

const { SERVICE_LISTS, SCHOOL_NAMES, schoolOf } = await appData({ 'data/chantLookup': ['SERVICE_LISTS', 'SCHOOL_NAMES', 'schoolOf'] });
const OUT = path.join(ROOT, 'src', 'data', 'humIndex.ts');
const N = 16;

const read = (book, num) => {
  const f = path.join(ROOT, 'public', 'notes', book, `${String(num).padStart(3, '0')}.json`);
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : null;
};
/** the top voice as one line: where it splits, the upper note; a repeated pitch once */
const topPitches = score => {
  const list = [...(score.voices?.[0] || [])].sort((a, b) => a[0] - b[0] || b[2] - a[2]);
  const out = [];
  list.filter((n, i) => i === 0 || n[0] !== list[i - 1][0]).forEach(n => { if (out[out.length - 1] !== n[2]) out.push(n[2]); });
  return out.slice(0, N);
};

const rows = [];
for (const [service, chants] of SERVICE_LISTS) {
  for (const chant of chants) {
    for (const v of chant.variants ?? []) {
      if (!v.bookNums?.length || /^a\d+$/.test(v.book ?? '')) continue;
      const score = read(v.book ?? 'book', v.bookNums[0]);
      const m = score && topPitches(score);
      if (!m || m.length < 6) continue;
      rows.push({ c: chant.id, v: v.id, t: chant.title.replace(/[;\s]+$/, ''), s: service, sc: SCHOOL_NAMES[schoolOf(v.code)] ?? '', m });
      break;
    }
  }
}

const q = s => JSON.stringify(s);
const body = `// Generated by \`node scripts/build-hum-index.mjs\` — never edit by hand.
// „ძებნა სიმღერით“: each chant's top voice, first ${N} pitches (MIDI, a repeated pitch once), from its first version with book notes.
export interface HumEntry { c: string; v: string; t: string; s: string; sc: string; m: number[] }

export const HUM_INDEX: readonly HumEntry[] = [
${rows.map(r => `{c:${q(r.c)},v:${q(r.v)},t:${q(r.t)},s:${q(r.s)},sc:${q(r.sc)},m:[${r.m.join(',')}]},`).join('\n')}
];
`;
fs.writeFileSync(OUT, body);
console.log(`${rows.length} chants → ${path.relative(ROOT, OUT)} (${(body.length / 1024).toFixed(0)} KB)`);
