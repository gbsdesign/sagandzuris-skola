// The folk songs' words for „გააგრძელე!“ (2026-11-01): every song of data/songsData.ts with a text — its own `lyrics`, else
// public/song-texts/<id>.json (the text the song's page shows) — cut into the lines that are sung (utils/lyricLines.ts: no
// singers' labels, numbers or repeat marks; a line that only repeats the title goes too). A song is kept when the game can ask
// it: a line sung once whose line before is sung once too, and three more full lines of it, none alike, to offer beside it
// (utils/gagrdzele.ts `cutsOf`, `drawGagrdzele` — tried with a few seeds).
// Writes src/data/lyricsPool.ts — run it again after a song's text changes:
//   node scripts/build-lyrics-pool.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { appData } from './print-games/appData.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'data', 'lyricsPool.ts');
const TEXTS = path.join(ROOT, 'public', 'song-texts');

const { FOLK_SONGS, lyricLines, lineKey, drawGagrdzele, mulberry32 } = await appData({
  'data/songsData.ts': ['FOLK_SONGS'],
  'utils/lyricLines.ts': ['lyricLines', 'lineKey'],
  'utils/gagrdzele.ts': ['drawGagrdzele'],
  'utils/otkheuli.ts': ['mulberry32'],
});
const playable = (id, lines) => Array.from({ length: 12 }, (_, seed) =>
  drawGagrdzele({ songs: [{ id, title: id, lines }], count: 1, rnd: mulberry32(seed + 1) }).length).some(Boolean);

const rows = [];
const left = [];
for (const s of FOLK_SONGS) {
  if (s.ownerOnly) continue;
  const file = path.join(TEXTS, `${s.id}.json`);
  const text = s.lyrics ?? (fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')).text : null);
  if (!text) continue;
  const lines = lyricLines(text).filter(l => lineKey(l) !== lineKey(s.title));
  if (playable(s.id, lines)) rows.push({ id: s.id, lines });
  else left.push(s.id);
}

const body = `// Generated by \`node scripts/build-lyrics-pool.mjs\` — never edit by hand.
// „გააგრძელე!“: the folk songs' words line by line (data/songsData.ts \`lyrics\`, public/song-texts/<id>.json), the songs the game
// can ask (utils/gagrdzele.ts).

export const LYRICS_POOL: readonly { id: string; lines: readonly string[] }[] = [
${rows.map(r => `  { id: ${JSON.stringify(r.id)}, lines: [\n${r.lines.map(l => `    ${JSON.stringify(l)},`).join('\n')}\n  ] },`).join('\n')}
];
`;
fs.writeFileSync(OUT, body);
console.log(`${rows.length} songs, ${rows.reduce((n, r) => n + r.lines.length, 0)} lines → ${path.relative(ROOT, OUT)}; left out: ${left.length}`);
