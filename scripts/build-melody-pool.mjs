// The melodies of „ექო“ and „მფრინავი ნოტები“ (2026-11-01): the well-known chants of the chant games (data/chantGamePool.ts,
// the pearls' nameable ones) and the admission program's folk songs that have book notes (data/songBookChants.ts), read from
// their book notes (public/notes/<book>/NNN.json — the very files the synthesizer plays): the top voice (the melody) and the
// bass as they sound, a note sung again on the same pitch once (the games ask the steps of a melody, not its rhythm), the
// first MAX notes of each. A chant sung in two versions is one name (the first version kept). Writes src/data/melodyPool.ts:
//   node scripts/build-melody-pool.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CHANTS, SONGS } from './print-games/melodies.mjs';
import { lineOf } from './print-games/music.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'data', 'melodyPool.ts');
const MAX = 40;

/** a voice's pitches in order, a repeated one once */
const stepsOf = (score, voice) => {
  const out = [];
  for (const n of lineOf(score, voice)) if (out[out.length - 1] !== n.midi) out.push(n.midi);
  return out.slice(0, MAX);
};

const rows = [...CHANTS, ...SONGS].flatMap(p => {
  const top = stepsOf(p.score, 0);
  const bass = stepsOf(p.score, p.score.voices.length - 1);
  if (top.length < 8 || bass.length < 8) return [];
  return [{ id: p.key, title: p.title, where: p.where, ref: p.ref, ...(p.kind === 'song' ? { song: true } : {}), top, bass }];
});

const q = s => JSON.stringify(s);
const body = `// Generated by \`node scripts/build-melody-pool.mjs\` — never edit by hand.
// „ექო“ and „მფრინავი ნოტები“: the melodies of the app's well-known chants and the program's songs from their book notes — the
// top voice and the bass as they sound (MIDI), a repeated pitch once, the first ${MAX} notes.
import type { Melody } from '../utils/eqo';

export const MELODY_POOL: readonly Melody[] = [
${rows.map(r => `  { id: ${q(r.id)}, title: ${q(r.title)}, where: ${q(r.where)}, ref: ${q(r.ref)},${r.song ? ' song: true,' : ''} top: [${r.top.join(', ')}], bass: [${r.bass.join(', ')}] },`).join('\n')}
];
`;
fs.writeFileSync(OUT, body);
console.log(`${rows.length} melodies (${rows.filter(r => r.song).length} songs) → ${path.relative(ROOT, OUT)}`);
