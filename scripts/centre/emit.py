"""Folklore Centre songs, step 3 of 3: <folder>/plan.json (songs.py) → src/data/centreSongs.ts + public/centre/<folder id>.json."""
import collections, json, os, re, sys

INV = sys.argv[1]
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
plan = json.load(open(f'{INV}/plan.json'))
existing_ids = {s['id'] for s in json.load(open(f'{INV}/songs.json'))['songs']}

# albums, sorted the way people read them (Georgian alphabetical, numbers first)
albums = sorted(plan['albums'], key=lambda a: a['name'])
index = {a['name']: i for i, a in enumerate(albums)}

# ── album files ──
out = f'{REPO}/public/centre'
os.makedirs(out, exist_ok=True)
for f in os.listdir(out):
    if f.endswith('.json'): os.remove(f'{out}/{f}')
for a in albums:
    # [id, title, note?, the same recording's file already on the site?]
    tracks = [[t[0], t[1]] + ([t[2], t[3]] if t[3] else [t[2]] if t[2] else []) for t in a['tracks']]
    json.dump({'name': a['name'], 'tracks': tracks}, open(f"{out}/{a['id']}.json", 'w'), ensure_ascii=False, separators=(',', ':'))

# ── song takes ──
TR = dict(zip('აბგდევზთიკლმნოპჟრსტუფქღყშჩცძწჭხჯჰ', 'a b g d e v z t i k l m n o p j r s t u p k g k s c c z c c x j h'.split()))
RC = {'guria': 'gu', 'kakheti': 'ka', 'shidakartli': 'sk', 'kvemokartli': 'kk', 'imereti': 'im', 'racha': 'ra', 'svaneti': 'sv',
      'samegrelo': 'sm', 'abkhazeti': 'ab', 'achara': 'ac', 'samtskhe': 'ms', 'mtianeti': 'mt', 'kalakuri': 'ql', 'lazeti': 'lz', 'oseti': 'os'}
def slug(t):
    s = ''.join(TR.get(c, c if c.isascii() and c.isalnum() else '-') for c in t.lower())
    return re.sub(r'-+', '-', s).strip('-')[:40] or 'song'

def take(b):
    f = b['all'] if not b['voices'] else [b['all'] or 0] + [v or 0 for v in b['voices']]
    t = [f, index[b['album']]]
    if b['note']: t.append(b['note'])
    return t

to_existing = collections.defaultdict(list)
new = collections.OrderedDict()
for b in sorted(plan['binds'], key=lambda b: (b['region'], b['key'], index[b['album']])):
    if b['song']:
        to_existing[b['song']].append(take(b))
    else:
        k = (b['region'], b['area'], b['key'])
        new.setdefault(k, {'titles': collections.Counter(), 'takes': []})
        new[k]['titles'][b['title']] += 1
        new[k]['takes'].append(take(b))

used = set(existing_ids)
rows = []
for (region, area, key), v in new.items():
    title = v['titles'].most_common(1)[0][0]
    base = f"fc-{slug(title)}-{RC[region]}"
    sid, n = base, 2
    while sid in used: sid, n = f'{base}-{n}', n + 1
    used.add(sid)
    rows.append([sid, title, region, area or 0, v['takes']])

def js(x): return json.dumps(x, ensure_ascii=False, separators=(',', ':'))
lines = [
    '// GENERATED by scripts/centre/songs.py — the Folklore Centre\'s songs in the school\'s Drive („ფოლკლორის ცენტრი / სიმღერები“,',
    '// one folder per album). Never edit by hand: change the script and run it again.',
    '// • CENTRE_SONG_ALBUMS: every album (Drive folder id, name, how many recordings). Its list of recordings is',
    '//   public/centre/<folder id>.json, fetched when the album is opened (pages: components/maps/SongAlbumPage.tsx).',
    '// • The recordings whose song is certain join the songs (songsData.ts): a song the app has (CENTRE_TAKES_OF) or a new',
    '//   one in its region (CENTRE_NEW_SONGS). Certain = the album is one region\'s (an expedition, a collection, a region\'s',
    '//   disc), the file names the region („(გურული)“, „კახეთი. სიღნაღი. …“), a local ensemble sings a song its region has, or',
    '//   the title is a song only one region has. Files already on the site (same size) are left out. The rest stay in',
    '//   their albums, from where the owner and the superadmins move them („გადატანა“, data/placements.ts).',
    "import type { FolkRegionId } from './songsData';",
    '',
    '/** A take: its Drive file id — or [full, I, II, III] for a learning album\'s take split by voices (0 = none) —, the',
    ' *  album (index into CENTRE_SONG_ALBUMS) and a note from the file name (performer, village) */',
    'export type CentreTake = [file: string | (string | 0)[], album: number, note?: string];',
    '',
    f'/** {len(albums)} albums: Drive folder id, name, number of recordings */',
    'export const CENTRE_SONG_ALBUMS: [id: string, name: string, count: number][] = [',
]
lines += [f"  {js([a['id'], a['name'], len(a['tracks'])])}," for a in albums]
lines += ['];', '', '/** a song the app already has → the Centre\'s takes of it */', 'export const CENTRE_TAKES_OF: Record<string, CentreTake[]> = {']
lines += [f"  {js(k)}: {js(v)}," for k, v in sorted(to_existing.items())]
lines += ['};', '', '/** new songs: id, title, region, sub-area (0 = none), takes */',
          'export const CENTRE_NEW_SONGS: [id: string, title: string, region: FolkRegionId, area: string | 0, takes: CentreTake[]][] = [']
lines += [f"  {js(r)}," for r in rows]
lines += ['];', '']
open(f'{REPO}/src/data/centreSongs.ts', 'w').write('\n'.join(lines))
print('albums', len(albums), '| existing songs', len(to_existing), '| new songs', len(rows),
      '| takes', sum(len(v) for v in to_existing.values()) + sum(len(r[4]) for r in rows))
print('ts bytes', os.path.getsize(f'{REPO}/src/data/centreSongs.ts'), '| album json total', sum(os.path.getsize(f'{out}/{f}') for f in os.listdir(out)))
