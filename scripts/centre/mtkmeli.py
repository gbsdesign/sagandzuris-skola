"""Folklore Centre, „სხვა“ → the მთქმელი section and the instruments: called by emit.py, writes src/data/centreOther.ts.

• CENTRE_MTKMELI_ALBUMS: the albums under the მთქმელი map (songs.py MTKMELI) — the poets' disc „ლექსის თქმა მწადის ერთისა“
  (named after Vakhushti Kotetishvili's 1987 collection) and an ensemble's talk about its village's ways.
• CENTRE_RECITERS: the disc's voices as მელექსეები, each with the poems they say. The file names give who says a poem
  („ივანე წიკლაური - …“); Kotetishvili (a scholar, not a mountain poet) reads some of them: a poem he names by its author
  („ი. ბაიაშვილის …“) goes to that author, the rest to „ხალხური ლექსები“. The disc is Pshav-Khevsur poetry, so everyone is
  in მცხეთა-მთიანეთი; a sub-area only where it is known (PLACE). The web had nothing on the others (checked 2026-10-29).
• CENTRE_INSTRUMENT_TAKES: songs.py INSTRUMENT — recordings shown in an instrument's window (views/SakravebiView.tsx)."""
import collections, json, re

READER = 'ვახუშტი კოტეტიშვილი'
AUTHOR_OF = [(re.compile(r'^ი\.\s?ბაიაშვილის\s+'), 'იოსებ ბაიაშვილი'), (re.compile(r'^ივ\.\s?წიკლაურის\s+'), 'ივანე წიკლაური')]
FOLK = 'ხალხური ლექსები'
GROUPS = {'': FOLK, 'ფშაველი მელექსეები': FOLK}
SKIP = {'შესავალი'}  # the disc's spoken opening: in the album only
PLACE = {'ივანე წიკლაური': 'გუდამაყარი'}  # Shalva Aslanishvili's 1949 recording: „გუდამაყარი, სოფ. გამსი, ივანე წიკლაური“
RECITERS_ALBUM = 'ლექსის თქმა მწადის ერთისა'


def reciters(album):
    people = collections.defaultdict(list)
    for fid, title, who in album['tracks']:
        note = ''
        if who == READER:
            if title in SKIP: continue
            note = f'კითხულობს {READER}'
            name = FOLK
            for rx, author in AUTHOR_OF:
                if rx.match(title): title, name = rx.sub('', title), author
        elif who in GROUPS:
            name, note = GROUPS[who], who
        else:
            name = who
        people[name].append([fid, title] + ([note] if note else []))
    return sorted(people.items(), key=lambda p: (p[0] == FOLK, p[0]))


def write(plan, repo, slug, js):
    albums = sorted(plan.get('mtkmeli', []), key=lambda a: a['name'])
    disc = next((a for a in albums if a['name'] == RECITERS_ALBUM), None)
    people = reciters(disc) if disc else []
    inst = collections.defaultdict(list)
    for i in plan.get('instruments', []):
        inst[i['instrument']].append([i['file'], i['title'], i['album'], i['name'], i['note']])
    lines = [
        "// GENERATED by scripts/centre/emit.py (scripts/centre/mtkmeli.py) — „ფოლკლორის ცენტრი / სხვა“: the მთქმელი section's",
        '// albums and voices, and the instruments\' recordings. Never edit by hand: change the script and run it again.',
        "import type { FolkRegionId } from './songsData';",
        '',
        '/** a poem said on a recording: Drive file id, title, a note (who reads it, when not the poet) */',
        'export type CentrePoem = [file: string, title: string, note?: string];',
        '',
        f'/** {len(albums)} albums under the მთქმელი map: Drive folder id, name, number of recordings (list: public/centre/<id>.json) */',
        'export const CENTRE_MTKMELI_ALBUMS: [id: string, name: string, count: number][] = [',
    ]
    lines += [f"  {js([a['id'], a['name'], len(a['tracks'])])}," for a in albums]
    lines += ['];', '', '/** the album the voices below come from (their rights are that album\'s) */',
              f"export const CENTRE_RECITERS_ALBUM = {js(disc['id'] if disc else '')};", '',
              '/** მელექსეები: id, name, region, sub-area (0 = none), poems; „rc-folk“ = the poems of no named poet */',
              'export const CENTRE_RECITERS: [id: string, name: string, region: FolkRegionId, area: string | 0, poems: CentrePoem[]][] = [']
    lines += [f"  {js(['rc-folk' if n == FOLK else 'rc-' + slug(n), n, 'mtianeti', PLACE.get(n, 0), poems])}," for n, poems in people]
    lines += ['];', '', '/** instrument id (data/instrumentsData.ts) → its recordings: file, title, album folder id, album name, note */',
              'export const CENTRE_INSTRUMENT_TAKES: Record<string, [file: string, title: string, album: string, albumName: string, note: string][]> = {']
    lines += [f"  {js(k)}: {js(v)}," for k, v in sorted(inst.items())]
    lines += ['};', '']
    open(f'{repo}/src/data/centreOther.ts', 'w').write('\n'.join(lines))
    return albums, len(people), sum(len(p) for _, p in people)
