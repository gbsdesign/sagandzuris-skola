export type PlayMode = 'notes' | 'even' | 'arp';

/** ABC notation without the X: line: header lines (L:, M:, K:…), then the music */
export interface StaffSpec {
  abc: string;
  cap?: string;
  /** 'notes' — the rhythm as written; 'even' — steady steps; 'arp' — each chord note by note, then together */
  play?: PlayMode | false;
  /** quarter notes a minute ('notes') */
  tempo?: number;
  /** a dictation: the notes stay covered until asked */
  hide?: boolean;
  /** a button for each voice alone */
  voices?: string[];
  /** a button that sounds every voice's first note together (as a dictation is begun) */
  start?: boolean;
}

export interface KeysSpec { from?: string; to?: string; mark?: string[]; cap?: string }

export interface Exercise {
  q: string;
  /** shown with the question (not played) */
  abc?: string;
  a: string;
  aAbc?: string;
  play?: PlayMode | false;
}

export type Block =
  | { h: string }
  | { p: string }
  | { list: string[] }
  | { steps: string[] }
  | { table: string[][]; head?: string[] }
  | { staff: StaffSpec }
  | { keys: KeysSpec }
  | { tip: string }
  | { exam: string; staff?: StaffSpec }
  | { ex: Exercise[] };

export interface Lesson {
  id: string;
  title: string;
  sub: string;
  /** the task of the university's test this lesson teaches (1–7) */
  task?: number;
  blocks: Block[];
}

// ---------- helpers ----------

const n = note;
const names = (ns: Note[]) => ns.map(syl).join(', ');
const dash = (ns: Note[]) => ns.map(syl).join('–');
const letters = (ns: Note[]) => ns.map(letter).join(' ');
const seq = (ns: Note[]) => ns.map(x => abc(x)).join(' ');
const stack = (ns: Note[]) => `[${ns.map(x => abc(x)).join('')}]`;
const WHOLE = 'L:1/1\nK:C';

// the test's rows: the given notes with their labels under them, and the same row answered
const intervalRow = (items: [string, string][]) => {
  const xs = items.map(([g, l]) => ({ g: n(g), l, a: interval(n(g), l) }));
  return {
    q: `${WHOLE}\n${xs.map(x => `"_${x.l}"${abc(x.g)}`).join(' | ')} |]`,
    a: `${WHOLE}\n${xs.map(x => `"_${x.l}"${stack([x.g, x.a])}`).join(' | ')} |]`,
    text: xs.map((x, i) => `${i + 1}) ${dash([x.g, x.a])}`).join(' · '),
  };
};

const chordRow = (items: [string, ChordKind, ChordShape][]) => {
  const xs = items.map(([g, k, s]) => ({ label: `${k} ${s}`, c: chord(n(g), k, s) }));
  return {
    q: `${WHOLE}\n${xs.map(x => `"_${x.label}"${abc(x.c[0])}`).join(' | ')} |]`,
    a: `${WHOLE}\n${xs.map(x => `"_${x.label}"${stack(x.c)}`).join(' | ')} |]`,
    text: xs.map((x, i) => `${i + 1}) ${x.label}: ${dash(x.c)}`).join(' · '),
  };
};

/** a scale in whole notes; `mark` puts a word above one of its notes */
const scaleAbc = (sc: Note[], mark?: [index: number, word: string], naturals = false) =>
  `${WHOLE}\n${sc.map((x, i) => (mark && mark[0] === i ? `"^${mark[1]}"` : '') + abc(x, naturals && x.alt === 0)).join(' ')} |]`;

const modeExercise = (tonic: string, mode: ModeName, minorLike: boolean): Exercise => {
  const sc = scale(n(tonic), mode);
  return { q: `**${tonicName(n(tonic), minorLike)}** — ${mode}`, a: `${letters(sc)} — ${names(sc)}.`, aAbc: scaleAbc(sc), play: 'even' };
};

