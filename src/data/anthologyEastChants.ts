import type { AnthPiece } from './anthologyChants';

type P = [string, number, string?];
const fileOf = (vol: number, num: string) => {
  const m = /^(\d+)([a-z]?)/.exec(num)!;
  return m[2] ? Number(m[1]) * (vol >= 4 ? 100 : 10) + m[2].charCodeAt(0) - 96 : Number(m[1]);
};
const east = (vol: number, ps: P[]): AnthPiece[] =>
  ps.map(([num, page, version = '']) => ({ vol, num, file: fileOf(vol, num), page, version, source: version || undefined, east: true }));

