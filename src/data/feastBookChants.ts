// The opening words (or a remark such as "წმიდაო ღმერთოს მაგიერ") go where the manuscript name of vol. I goes:
// under the button and in the synthesizer header; the Karbelashvili-mode chants of vol. VII follow as a ქართლ-კახური row
export const SADGHESASWAULO_CHANTS: ChantItem[] = withKarbelaantFeasts(FEASTS.map(([title, chants], i) => ({
  id: `sd-${i + 1}`,
  index: i + 1,
  title,
  variants: chants.map(([version, num, incipit], vi) => {
    const page = PAGES[num];
    const name = variantName({ bookNums: [num], version });
    return {
      id: `sd-v-${i + 1}-${vi + 1}`,
      code: chants.length > 1 ? `გ.ს. №${num}` : 'გ.ს.',
      label: 'გელათის სკოლა',
      chantName: title,
      fullTitle: `გ.ს. ${title.split(' — ')[0]} (${[name, incipit && `„${incipit}"`, `გვ. ${page}`].filter(Boolean).join(', ')})`,
      version,
      page,
      bookNums: [num],
      source: incipit,
      book: BOOK,
    };
  }),
})));
