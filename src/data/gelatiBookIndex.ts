export const SOURCE_NAMES: Record<string, string> = { 'ხ': 'ხუნდაძე', 'კ': 'კერესელიძე', 'ქ': 'ქორიძე' };

export type BookNums = number | [from: number, to: number];
export const numsOf = (n: BookNums): number[] =>
  typeof n === 'number' ? [n] : Array.from({ length: n[1] - n[0] + 1 }, (_, i) => n[0] + i);

export const bookPage = (num: number) => PAGES[num];

// "145", or "149–152" for a version made of several numbers
export const bookNumLabel = (nums?: number[]) =>
  !nums?.length ? '' : nums.length > 1 ? `${nums[0]}–${nums[nums.length - 1]}` : String(nums[0]);
// Source of a version = the first of its numbers that names one
export const bookSource = (nums: number[]): string | undefined => {
  const c = nums.map(n => SOURCES[n]).find(s => s && s !== '-');
  return c ? SOURCE_NAMES[c] : undefined;
};
