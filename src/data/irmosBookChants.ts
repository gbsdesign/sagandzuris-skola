const build = (prefix: string, groups: IrmosGroup[]): ChantItem[] => groups.map(([title, model, chants], i) => ({
  id: `${prefix}-${i + 1}`,
  index: i + 1,
  title,
  model: model || undefined,
  variants: chants.map(([version, num, page, incipit], vi) => ({
    id: `${prefix}-v-${i + 1}-${vi + 1}`,
    code: `${V8_SCHOOL} №${num}`,
    label: 'რვახმა საცისკრო ძლისპირები',
    chantName: title,
    fullTitle: `${title} (${[variantName({ version }), incipit && `„${incipit}"`, `გვ. ${page}`].filter(Boolean).join(', ')})`,
    version,
    page,
    bookNums: [num],
    source: incipit || undefined,
    book: BOOK,
  })),
}));

