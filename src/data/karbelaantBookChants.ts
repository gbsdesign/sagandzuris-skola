// The opening words (or the kind of chant) go under the button and in the synthesizer header, as in vols. II and IV
const karbVariant = (prefix: string, index: number, title: string, [version, num, note]: KarbChant, many: boolean): ChantVariant => {
  const page = PAGES[num];
  const name = variantName({ bookNums: [num], version });
  return {
    id: `${prefix}-v-${index}-kb${num}`,
    code: many ? `ქ.კ. №${num}` : 'ქ.კ.',
    label: 'ქართლ-კახური',
    chantName: title,
    fullTitle: `ქ.კ. ${title.split(' — ')[0]} (${[name, note && (prefix === 'sd' ? `„${note}"` : note), `გვ. ${page}`, 'კარბელაანთ კილო'].filter(Boolean).join(', ')})`,
    version,
    page,
    bookNums: [num],
    source: note,
    book: KARB_BOOK,
  };
};

const withKarbelaant = (prefix: string, table: Record<number, KarbChant[]>) => (items: ChantItem[]): ChantItem[] =>
  items.map(item => {
    const chants = table[item.index];
    if (!chants) return item;
    return { ...item, variants: [...item.variants, ...chants.map(c => karbVariant(prefix, item.index, item.title, c, chants.length > 1))] };
  });

export const withKarbelaantFeasts = withKarbelaant('sd', FEASTS);
export const withKarbelaantLent = withKarbelaant('mx', LENT);
export const withKarbelaantPascha = withKarbelaant('zt', PASCHA);
