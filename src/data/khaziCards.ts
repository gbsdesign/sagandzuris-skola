/** the first year of „1837–1907“; „XII საუკუნე“ or „დ. 1956“ give no card */
const bornIn = (years?: string) => { const m = years?.match(/^(\d{3,4})\s*[–-]/); return m ? Number(m[1]) : null; };

const PEOPLE: KhaziCard[] = [
  ...MTKMELI_AUTHORS.flatMap(a => {
    const y = bornIn(a.years);
    return y ? [{ id: `a-${a.id}`, deck: 'adamianebi' as const, text: `დაიბადა ${a.name}`, when: y, label: String(y), note: a.about, icon: 'feather' as const }] : [];
  }),
  ...ANCESTORS.flatMap(a => {
    const y = bornIn(a.years);
    return y ? [{
      id: `w-${a.id}`, deck: 'adamianebi' as const, text: `დაიბადა ${a.name}`, when: y, label: String(y), icon: 'music' as const,
      note: a.group === 'hymnographers' ? 'ჰიმნოგრაფი — საგალობლების ავტორი.' : 'გალობის შემნახველი და მასწავლებელი.',
    }] : [];
  }),
];

