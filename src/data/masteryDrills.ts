import type { Drill } from './vocalDrills';

/** an exercise the app runs itself (components/mastery/trainers) */
export type TrainerSpec =
  | { kind: 'higher' }
  | { kind: 'interval-id'; set: number[] }
  | { kind: 'interval-sing'; set: number[]; both?: boolean; strict?: boolean }
  | { kind: 'echo'; notes: number; from: 'scale' | 'chant' | 'turn' }
  | { kind: 'home' }
  | { kind: 'dict'; notes: number; two?: boolean }
  | { kind: 'rhythm-copy' }
  | { kind: 'rhythm-dict' }
  | { kind: 'tempo' }
  | { kind: 'chord-id'; kinds: string[] }
  | { kind: 'chord-sing' }
  | { kind: 'read'; notes: number }
  | { kind: 'hold'; mode: 'steady' | 'straight' | 'swell'; seconds: number }
  | { kind: 'siren' }
  | { kind: 'breath' }
  | { kind: 'drone-hold' }
  | { kind: 'along'; shift: number; timed?: boolean }
  | { kind: 'letters' }
  | { kind: 'tones' }
  | { kind: 'schools' }
  | { kind: 'listen' };

/** an exercise done elsewhere in the app; the student ticks it here */
export type OpenSpec =
  | { kind: 'learn'; voice: '1' | '2' | '3' }
  | { kind: 'game'; item: string; name: string }
  | { kind: 'sight' }
  | { kind: 'review' };

const trainer = (id: string, title: string, minutes: number, lesson: Drill['lesson'], spec: TrainerSpec): Drill =>
  ({ id, title, lesson, exercise: { title, minutes, steps: [] }, trainer: spec });
const opens = (id: string, title: string, minutes: number, lesson: Drill['lesson'], spec: OpenSpec): Drill =>
  ({ id, title, lesson, exercise: { title, minutes, steps: [] }, open: spec });
const reading = (id: string, title: string, minutes: number, lesson: Drill['lesson']): Drill =>
  ({ id, title, lesson, exercise: { title, minutes, steps: [] }, read: true });

