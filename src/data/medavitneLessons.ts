// Text marks: **bold**.

export type LessonStep =
  | { kind: 'learn'; title: string; body: string[]; points?: string[] }
  /** an order to follow: a service's parts, the way to read a kathisma */
  | { kind: 'order'; title: string; intro?: string; items: [name: string, note?: string][] }
  /** a text to read aloud, with the recorder under it */
  | { kind: 'read'; title: string; intro?: string; lines?: string[]; psalms?: number[]; bible?: { book: string; name: string; ch: number; from: number; to: number } }
  | { kind: 'quiz'; question: string; options: string[]; answer: number; explain: string }
  | { kind: 'task'; title: string; body: string[]; open?: 'psalter' }

export interface Lesson {
  id: string;
  title: string;
  sub: string;
  minutes: number;
  steps: LessonStep[];
}

