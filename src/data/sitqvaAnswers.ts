const of = (kind: SitqvaKind, words: string[]) =>
  words.filter(w => w.length >= 4 && w.length <= 6).map(word => ({ word, kind }));

/** every word once: a word in two lists („მიმინო“ — a bird and a film, „პური“ — the table and the church) keeps its first kind */
export const ANSWER_BANK: SitqvaCandidate[] = [
  ...of('region', REGION), ...of('food', FOOD), ...of('nature', NATURE), ...of('hero', HERO), ...of('culture', CULTURE),
  ...of('church', CHURCH),
].filter((c, i, all) => all.findIndex(x => x.word === c.word) === i);

/** the words a guess may always be, even when the dictionary did not load */
export const ANSWER_WORDS = new Set(ANSWER_BANK.map(c => c.word));
