export interface TabuEntry extends TabuCard {
  theme: string;
  /** the card's place in the bank: theme's index × 100 + its own, stable while cards are only added at a theme's end */
  id: number;
}

export const TABU_CARDS: readonly TabuEntry[] = TABU_THEMES.flatMap((t, ti) => t.cards.map((card, i) => ({ ...card, theme: t.id, id: ti * 100 + i })));
export const tabuTheme = (id: string) => TABU_THEMES.find(t => t.id === id);
