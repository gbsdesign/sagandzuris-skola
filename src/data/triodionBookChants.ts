// The kind (and, for repeated chants, the source) goes where the manuscript name of vol. I goes:
// under the button and in the synthesizer header
const build = (prefix: string, occasions: Occasion[]): ChantItem[] =>
  occasions.map(([title, chants], i) => ({
    id: `${prefix}-${i + 1}`,
    index: i + 1,
    title,
    variants: chants.map(([version, num, kind, from], vi) => {
      const page = PAGES[num];
      const source = [kind, from].filter(Boolean).join(', ') || undefined;
      const name = variantName({ bookNums: [num], version });
      return {
        id: `${prefix}-v-${i + 1}-${vi + 1}`,
        code: chants.length > 1 ? `გ.ს. №${num}` : 'გ.ს.',
        label: 'გელათის სკოლა',
        chantName: title,
        fullTitle: `გ.ს. ${title} (${[name, source, `გვ. ${page}`].filter(Boolean).join(', ')})`,
        version,
        page,
        bookNums: [num],
        source,
        book: BOOK,
      };
    }),
  }));

