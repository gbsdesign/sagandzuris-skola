import type { RoundAnswer, RoundRules } from './roundGames';
import { fullLine, lineKey } from './lyricLines';

// „გააგრძელე!“ (2026-11-01, the plan's №10, like Don't Forget the Lyrics!): a folk song's beginning sounds (when its recording
// may be heard) and stops; the title and the line or two before a gap show — which line comes next? Online and alone: four
// lines of the same song to pick from, the right one 1000 at once, 500 at the last moment. On one phone the teams sing or
// write it from memory and the host compares it with the true line. One round of the quick games (utils/roundGames.ts); the
// songs' lines data/lyricsPool.ts (generated by scripts/build-lyrics-pool.mjs), the screens pages/games/gagrdzele/. Kept free
// of the songs' data: this file is in the app's first bundle (the room's store).

export interface GagrdzeleQ {
  kind: 'gagrdzele';
  /** the song and the line asked: `<song id>#<line index>` */
  id: string;
  song: string;
  /** where it is sung (a region's name) */
  where?: string;
  /** the line or two before the one asked */
  lines: string[];
  /** four lines of the song in the order shown; `right` is the next one */
  options: string[];
  right: number;
  /** the line after the answer (the reveal goes on with it) */
  after?: string;
  /** the song's recording: its beginning plays (`from` 0) */
  url?: string;
  from?: number;
}

/** the song's beginning heard, then the time to pick; without a recording only the time to read */
export const GAGRDZELE_CLIP = 12;
export const GAGRDZELE_SECONDS = 20;
export const gagrdzeleSeconds = (q: Pick<GagrdzeleQ, 'url'>) => (q.url ? GAGRDZELE_SECONDS + GAGRDZELE_CLIP : GAGRDZELE_SECONDS);
export const LINE_MAX = 160;

/** the right line: 1000 at once, 500 at the last moment */
export const gagrdzelePoints = (q: Pick<GagrdzeleQ, 'right'>, a: Pick<RoundAnswer, 'pick' | 'ms'>, limitMs: number) => {
  if (a.pick !== q.right) return 0;
  const late = limitMs > 0 ? Math.min(1, Math.max(0, a.ms / limitMs)) : 1;
  return Math.round(1000 - 500 * late);
};

const text = (v: unknown, max: number) => typeof v === 'string' && v.trim().length > 0 && v.length <= max;
const lineList = (v: unknown, min: number, max: number) => Array.isArray(v) && v.length >= min && v.length <= max && v.every(l => text(l, LINE_MAX));

export const GAGRDZELE_RULES: RoundRules<GagrdzeleQ> = {
  steps: () => 1,
  seconds: q => gagrdzeleSeconds(q),
  ok: (q, pick) => Number.isInteger(pick) && pick >= 0 && pick < q.options.length,
  points: gagrdzelePoints,
  secret: ['right', 'after'],
  valid: (q): q is GagrdzeleQ => {
    const o = q as Partial<GagrdzeleQ>;
    return !!o && o.kind === 'gagrdzele' && text(o.id, 200) && text(o.song, 120) && (o.where === undefined || text(o.where, 60))
      && lineList(o.lines, 1, 2) && lineList(o.options, 4, 4) && new Set(o.options!.map(lineKey)).size === 4
      && Number.isInteger(o.right) && o.right! >= 0 && o.right! < 4 && (o.after === undefined || text(o.after, LINE_MAX))
      && (o.url === undefined ? o.from === undefined : text(o.url, 400) && typeof o.from === 'number' && o.from >= 0 && o.from < 1);
  },
};

