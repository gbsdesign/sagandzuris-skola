// ——— a game's rounds

export interface LyricSong {
  id: string;
  title: string;
  where?: string;
  lines: readonly string[];
  /** its whole takes, when they may be heard */
  takes?: readonly { url: string }[];
}

/** where a song may be cut: the line asked and the one before it are each sung once in the song, the line asked is a full
 *  one; and the song's full lines sung once, to offer beside it */
export const cutsOf = (lines: readonly string[]) => {
  const count = new Map<string, number>();
  for (const l of lines) count.set(lineKey(l), (count.get(lineKey(l)) ?? 0) + 1);
  const once = (l: string) => count.get(lineKey(l)) === 1;
  const cuts: number[] = [];
  for (let i = 1; i < lines.length; i++) if (once(lines[i]) && fullLine(lines[i]) && once(lines[i - 1])) cuts.push(i);
  return { cuts, offers: lines.filter(l => once(l) && fullLine(l)) };
};

/** with a recording its beginning sounds first: the line asked comes from the fourth on, so the piece does not sing it */
export const HEARD_FROM = 3;

const shuffled = <T,>(list: readonly T[], rnd: () => number) => {
  const a = [...list];
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
};

export interface GagrdzeleDraw {
  songs: readonly LyricSong[];
  count: number;
  /** the songs asked lately on this phone, the oldest first: others first, then the oldest */
  seen?: readonly string[];
  rnd?: () => number;
}

/** two lines that read nearly the same (their letter pairs mostly shared): never offered side by side */
const pairs = (l: string) => {
  const k = lineKey(l);
  const m = new Map<string, number>();
  for (let i = 0; i + 1 < k.length; i++) m.set(k.slice(i, i + 2), (m.get(k.slice(i, i + 2)) ?? 0) + 1);
  return m;
};
export const alike = (a: string, b: string) => {
  const A = pairs(a);
  const B = pairs(b);
  let both = 0;
  let all = 0;
  for (const [g, n] of A) { both += Math.min(n, B.get(g) ?? 0); all += n; }
  for (const n of B.values()) all += n;
  return all > 0 && (2 * both) / all >= 0.6;
};

/** a game's rounds: a different song each, the songs not asked lately first; the line asked, the one or two before it, and
 *  three more lines of the same song to offer, none of the four alike */
export const drawGagrdzele = ({ songs, count, seen = [], rnd = Math.random }: GagrdzeleDraw): GagrdzeleQ[] => {
  const ready = songs.map(s => ({ s, ...cutsOf(s.lines) })).filter(x => x.cuts.length && x.offers.length >= 4);
  const at = new Map(seen.map((id, i) => [id, i]));
  const order = [
    ...shuffled(ready.filter(x => !at.has(x.s.id)), rnd),
    ...ready.filter(x => at.has(x.s.id)).sort((a, b) => at.get(a.s.id)! - at.get(b.s.id)!),
  ];
  const out: GagrdzeleQ[] = [];
  for (const { s, cuts, offers } of order) {
    if (out.length >= count) break;
    const take = s.takes?.length ? s.takes[Math.floor(rnd() * s.takes.length)] : null;
    // with a recording: a line from the fourth on, its beginning heard first; else (or none fits) any line, read only
    const tries: [number, boolean][] = take
      ? [...shuffled(cuts.filter(i => i >= HEARD_FROM), rnd).map(i => [i, true] as [number, boolean]),
        ...shuffled(cuts.filter(i => i < HEARD_FROM), rnd).map(i => [i, false] as [number, boolean])]
      : shuffled(cuts, rnd).map(i => [i, false]);
    for (const [i, heard] of tries) {
      const answer = s.lines[i];
      const shown = s.lines.slice(Math.max(0, i - 2), i);
      const shownKeys = new Set(shown.map(lineKey));
      const picked = [answer];
      for (const l of shuffled(offers, rnd)) {
        if (picked.length === 4) break;
        if (l !== answer && !shownKeys.has(lineKey(l)) && !picked.some(p => alike(p, l))) picked.push(l);
      }
      if (picked.length < 4) continue;
      const options = shuffled(picked, rnd);
      out.push({
        kind: 'gagrdzele', id: `${s.id}#${i}`.slice(0, 200), song: s.title, ...(s.where ? { where: s.where } : {}),
        lines: shown, options, right: options.indexOf(answer), ...(s.lines[i + 1] ? { after: s.lines[i + 1] } : {}),
        ...(take && heard ? { url: take.url, from: 0 } : {}),
      });
      break;
    }
  }
  return out;
};

/** the song's id from its round (the phone remembers the songs it asked) */
export const gagrdzeleSongOf = (q: Pick<GagrdzeleQ, 'id'>) => q.id.split('#')[0];
